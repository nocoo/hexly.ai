import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { readProjects } from "../src/data/read-projects";
import { projectTexture } from "../src/model/brand";

interface Provenance {
	version?: string;
	design?: {
		identityType?: string;
		language?: string;
		name?: Record<string, string>;
		description?: Record<string, string>;
	};
	contrast?: {
		lightMinimum?: number;
		darkMinimum?: number;
		lightFullCanvasMinimum?: number;
		darkFullCanvasMinimum?: number;
	};
	superseded?: string;
}

const projects = readProjects();
const profileFiles = new Map<string, string>();
for (const name of await readdir("docs/profiles")) {
	const id = name.match(/^\d+-(.+)\.md$/)?.[1];
	if (id) profileFiles.set(id, name);
}
const rows: {
	id: string;
	title: string;
	version: string;
	root: string;
	name: Record<string, string>;
	description: Record<string, string>;
	opacity: number;
	identityType: string;
	language: string;
	contrast: {
		light?: number;
		dark?: number;
		fullLight?: number;
		fullDark?: number;
	};
	history: number;
}[] = [];

for (const project of projects) {
	const texture = project.brandTexture ?? projectTexture(project);
	if (!texture) continue;
	const version: string | undefined =
		project.brandTexture?.version ?? project.brandKit?.version;
	if (!version) continue;
	const dir = `public/textures/${project.id}/v${version}`;
	let provenance: Provenance = {};
	if (existsSync(`${dir}/provenance.json`))
		provenance = JSON.parse(
			await readFile(`${dir}/provenance.json`, "utf8"),
		) as Provenance;
	const history = existsSync(`public/textures/${project.id}`)
		? (await readdir(`public/textures/${project.id}`)).filter((name) =>
				name.startsWith("v"),
			).length
		: 1;
	const root: string = texture.root;
	const name: Record<string, string> = provenance.design?.name ?? texture.name;
	const description: Record<string, string> =
		provenance.design?.description ?? texture.description;
	const opacity = project.brandTexture?.surfaceOpacity ?? 0;
	rows.push({
		id: project.id,
		title: project.title,
		version,
		root,
		name,
		description,
		opacity,
		identityType: provenance.design?.identityType ?? "unrecorded",
		language: provenance.design?.language ?? "unrecorded",
		contrast: {
			light: provenance.contrast?.lightMinimum,
			dark: provenance.contrast?.darkMinimum,
			fullLight: provenance.contrast?.lightFullCanvasMinimum,
			fullDark: provenance.contrast?.darkFullCanvasMinimum,
		},
		history,
	});
}

const types = new Map<string, number>();
for (const row of rows)
	types.set(row.identityType, (types.get(row.identityType) ?? 0) + 1);
const ratio = (value: number | undefined) =>
	value === undefined ? "—" : `${Number(value.toFixed(2))}:1`;
const profileLink = (id: string, title: string) =>
	profileFiles.has(id) ? `[${title}](profiles/${profileFiles.get(id)})` : title;

const lines = [
	"# Project texture packs",
	"",
	`Current decorative surface for ${rows.length} catalogue entries. Generated by \`bun run docs:textures\` from \`src/data/projects/\` and each pack's \`provenance.json\`; never edit this file by hand. Rules and procedure live in [the brand texture skill](../.agents/skills/hexly-brand-textures/SKILL.md), the rollout history in [the 2026-09-14 record](27-project-textures.md).`,
	"",
	"`Identity` is the recorded design language: animals and birds use habitat foliage, tools use a working surface or material. `Contrast` is measured on rendered pixels over the left 62% of the canvas, where text and controls actually sit; the full-canvas minimum is kept in each pack's provenance for reference, because the motif is decoration behind an empty column.",
	"",
	"| Identity | Packs |",
	"| --- | ---: |",
	...[...types.entries()]
		.sort((a, b) => b[1] - a[1])
		.map(([type, count]) => `| ${type} | ${count} |`),
	"",
	"| Project | Pack | Motif | 底纹 | Identity | Opacity | Contrast light/dark | Kept versions |",
	"| --- | --- | --- | --- | --- | ---: | --- | ---: |",
	...rows
		.sort((a, b) => a.id.localeCompare(b.id))
		.map(
			(row) =>
				`| ${profileLink(row.id, row.title)} | \`${row.version}\` | ${row.name?.en ?? "—"} | ${row.name?.zh ?? "—"} | ${row.identityType} / ${row.language} | ${row.opacity} | ${ratio(row.contrast.light)} · ${ratio(row.contrast.dark)} | ${row.history} |`,
		),
	"",
	"## Publication",
	"",
	"Each row maps to `public/textures/<id>/v<X.Y.Z>/` in Git and `projects/<id>/textures/v<X.Y.Z>/` in the immutable R2 `hexlyai` bucket at `https://h.no.mt`. Publish with `bun run assets:r2 -- publish --project <id> --upload`; superseded versions stay online for old links. The catalogue selects a pack through optional `Project.brandTexture`, so a texture-only revision never re-uploads identity bytes.",
	"",
];

await writeFile("docs/40-texture-packs.md", lines.join("\n"));
console.log(`Wrote docs/40-texture-packs.md for ${rows.length} packs.`);
